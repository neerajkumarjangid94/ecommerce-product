<?php

namespace App\Services;

use App\Models\Product;
use App\Models\Color;
use App\Models\Size;
use App\Models\ProductVariant;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;

class ProductService
{
    /**
     * Store a new product along with its images.
     *
     * @param  array  $data   Validated data from StoreProductRequest
     * @return Product
     */
    public function store(array $data): Product
    {
        return DB::transaction(function () use ($data) {

            // 1. Create the product record
            $product = Product::create([
                'name'        => $data['name'],
                'description' => $data['description'] ?? null,
                'is_active'   => $data['is_active'] ?? true,
            ]);

            // 2. Handle image uploads (if any)
            if (!empty($data['images'])) {
                $this->storeImages($product, $data['images']);
            }

            // 3. Handle Colors & Sizes Options
            $maps = $this->storeOptions($product, $data['color_ids'] ?? [], $data['size_ids'] ?? []);

            // 4. Handle Variants
            if (!empty($data['variants'])) {
                $this->storeVariants($product, $data['variants'], $maps);
            }

            return $product;
        });
    }

    /**
     * Store product images and mark the first one as primary.
     *
     * @param  Product            $product
     * @param  UploadedFile[]     $images
     * @return void
     */
    private function storeImages(Product $product, array $images): void
    {
        foreach ($images as $index => $image) {
            // Store file under storage/app/public/products/{product_id}/
            $path = $image->store("products/{$product->id}", 'public');

            $product->images()->create([
                'image_path' => $path,
                'is_primary' => $index === 0, // first uploaded image is primary
            ]);
        }
    }

    /**
     * Store product options mapping (Colors and Sizes) and return maps to map original attribute IDs to new option values.
     *
     * @param Product $product
     * @param array $colorIds
     * @param array $sizeIds
     * @return array
     */
    private function storeOptions(Product $product, array $colorIds, array $sizeIds): array
    {
        $colorMap = [];
        $sizeMap = [];

        if (!empty($colorIds)) {
            $colorOption = $product->options()->create(['name' => 'Color']);
            $colors = Color::whereIn('id', $colorIds)->get();
            foreach ($colors as $color) {
                $val = $colorOption->values()->create(['value' => $color->name]);
                $colorMap[$color->id] = [
                    'option_id' => $colorOption->id,
                    'option_value_id' => $val->id
                ];
            }
        }

        if (!empty($sizeIds)) {
            $sizeOption = $product->options()->create(['name' => 'Size']);
            $sizes = Size::whereIn('id', $sizeIds)->get();
            foreach ($sizes as $size) {
                $val = $sizeOption->values()->create(['value' => $size->name]);
                $sizeMap[$size->id] = [
                    'option_id' => $sizeOption->id,
                    'option_value_id' => $val->id
                ];
            }
        }

        return ['colorMap' => $colorMap, 'sizeMap' => $sizeMap];
    }

    /**
     * Store variants generated in UI.
     *
     * @param Product $product
     * @param array $variants
     * @param array $maps Maps generated by storeOptions to link UI IDs to DB Option IDs
     * @return void
     */
    private function storeVariants(Product $product, array $variants, array $maps): void
    {
        foreach ($variants as $v) {
            
            // Prefer the frontend generated SKU if it exists and is unique
            $sku = $v['sku'] ?? '';
            
            if (empty($sku) || ProductVariant::where('sku', $sku)->exists()) {
                // Generate a robust unique SKU for the variant as a fallback
                $prefix = strtoupper(Str::slug(substr($product->name, 0, 5))) ?: 'VAR';
                do {
                    $sku = $prefix . '-' . strtoupper(Str::random(6));
                } while (ProductVariant::where('sku', $sku)->exists());
            }

            $variant = $product->variants()->create([
                'sku' => $sku,
                'price' => $v['price'],
                'stock_quantity' => $v['stock'],
            ]);

            // Link color if present
            if (!empty($v['color_id']) && isset($maps['colorMap'][$v['color_id']])) {
                $mapped = $maps['colorMap'][$v['color_id']];
                $variant->optionValues()->create([
                    'option_id' => $mapped['option_id'],
                    'option_value_id' => $mapped['option_value_id'],
                ]);
            }

            // Link size if present
            if (!empty($v['size_id']) && isset($maps['sizeMap'][$v['size_id']])) {
                $mapped = $maps['sizeMap'][$v['size_id']];
                $variant->optionValues()->create([
                    'option_id' => $mapped['option_id'],
                    'option_value_id' => $mapped['option_value_id'],
                ]);
            }

            // Store variant image if present
            if (!empty($v['image'])) {
                $path = $v['image']->store("products/{$product->id}/variants", 'public');
                $variant->images()->create([
                    'image_path' => $path,
                    'is_primary' => true,
                    'sort_order' => 0,
                ]);
            }
        }
    }
}
